"""Writes a binary file as a C array, so the firmware carries it in flash.

    python3 -I embed.py <input> <output.h> <NAME>
"""

import sys
from pathlib import Path

data = Path(sys.argv[1]).read_bytes()
name = sys.argv[3]
lines = [", ".join(str(b) for b in data[i : i + 32]) for i in range(0, len(data), 32)]
body = ",\n  ".join(lines)
Path(sys.argv[2]).write_text(
    f"// Generated by device/firmware/embed.py from {Path(sys.argv[1]).name}; do not edit.\n"
    "#pragma once\n#include <stdint.h>\n\n"
    f"static const uint8_t {name}[{len(data)}] __attribute__((aligned(4))) = {{\n  {body}\n}};\n"
)
